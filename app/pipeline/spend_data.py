"""SYNTHETIC fixture dataset the worker agent's `query_spend` tool queries.

This is not live GCP billing data. It is a small, deterministic (fixed-seed) synthetic
cloud-spend table baked into the demo agent so the pipeline has something concrete and
checkable to reason about — the theme (cloud spend) mirrors this repo's sibling,
gcp-finops-cost-anomaly-detector, but the numbers here are entirely synthetic and exist
only to give the agent pipeline a genuine, gradeable task. Every row is generated by
`_generate()` below; nothing here is scraped or copied from any real billing export.
"""

from __future__ import annotations

import random
from dataclasses import dataclass

SERVICES = ["BigQuery", "Cloud Run", "Compute Engine", "Cloud Storage", "Vertex AI"]
MONTHS = ["2026-06", "2026-07", "2026-08"]

# Base monthly spend per service (USD) plus small deterministic day-to-day noise.
_BASE_USD = {
    "BigQuery": 420.0,
    "Cloud Run": 180.0,
    "Compute Engine": 610.0,
    "Cloud Storage": 95.0,
    "Vertex AI": 260.0,
}
# One deliberate month-over-month step so "which service grew the most" has a clean,
# single correct answer: Vertex AI usage triples from June to August.
_MONTH_MULTIPLIER = {
    "BigQuery": {"2026-06": 1.0, "2026-07": 1.05, "2026-08": 1.1},
    "Cloud Run": {"2026-06": 1.0, "2026-07": 0.95, "2026-08": 1.0},
    "Compute Engine": {"2026-06": 1.0, "2026-07": 1.02, "2026-08": 0.98},
    "Cloud Storage": {"2026-06": 1.0, "2026-07": 1.1, "2026-08": 1.2},
    "Vertex AI": {"2026-06": 1.0, "2026-07": 1.8, "2026-08": 3.0},
}


@dataclass(frozen=True)
class SpendRow:
    month: str
    service: str
    amount_usd: float


def _generate() -> list[SpendRow]:
    rng = random.Random(42)  # fixed seed: dataset is identical on every run
    rows: list[SpendRow] = []
    for month in MONTHS:
        for service in SERVICES:
            base = _BASE_USD[service] * _MONTH_MULTIPLIER[service][month]
            noise = rng.uniform(-0.03, 0.03)
            rows.append(SpendRow(month=month, service=service, amount_usd=round(base * (1 + noise), 2)))
    return rows


DATASET: list[SpendRow] = _generate()


def query_spend(service: str | None = None, month: str | None = None) -> dict:
    """The worker agent's only tool. Deterministic, no network I/O, no LLM call —
    the point is that the *agent* decides when to call it and what to ask, and the
    reviewer/judge can check the final answer against exactly what this returned."""
    rows = DATASET
    if service:
        rows = [r for r in rows if r.service.lower() == service.lower()]
    if month:
        rows = [r for r in rows if r.month == month]
    total = round(sum(r.amount_usd for r in rows), 2)
    return {
        "matched_rows": [r.__dict__ for r in rows],
        "total_usd": total,
        "row_count": len(rows),
    }


def total_by_service_across_months() -> dict:
    totals: dict[str, float] = {s: 0.0 for s in SERVICES}
    for r in DATASET:
        totals[r.service] += r.amount_usd
    return {s: round(v, 2) for s, v in totals.items()}


def growth_pct(service: str, from_month: str, to_month: str) -> float:
    a = next(r.amount_usd for r in DATASET if r.service == service and r.month == from_month)
    b = next(r.amount_usd for r in DATASET if r.service == service and r.month == to_month)
    return round((b - a) / a * 100, 1)
